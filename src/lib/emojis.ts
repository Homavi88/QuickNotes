/** Flat unique list (favorites first) for selects / search. */
export const PROJECT_EMOJIS: readonly string[] = (() => {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const e of cat.emojis) {
      if (!seen.has(e)) {
        seen.add(e);
        out.push(e);
      }
    }
  }
  return out;
})();
